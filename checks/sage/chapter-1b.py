def gap_chevalley(typ, r):
    """A simple algebra over QQ with a Chevalley basis [x_a], [y_a], [h_i] (GAP):
    returns the sizes and the Killing matrix in that basis, and the Cartan part."""
    L = libgap.SimpleLieAlgebra(typ, r, libgap.Rationals)
    ch = libgap.ChevalleyBasis(L)
    bas = libgap.Basis(L, libgap.Concatenation(ch))
    K = libgap.KillingMatrix(bas)
    n = int(libgap.Dimension(L))
    M = matrix(QQ, n, n, [QQ(x) for row in K.sage() for x in row])
    return L, ch, bas, M, int(libgap.Length(ch[0])), r


def gap_structure(typ, r, F):
    """The structure constants in GAP's Chevalley basis, over F (ZZ-integral)."""
    L = libgap.SimpleLieAlgebra(typ, r, libgap.Rationals)
    bas = libgap.Basis(L)
    els = [bas[i] for i in range(int(libgap.Length(bas)))]
    n = len(els)
    V = VS(F, n)
    t = [[V.zero() for _ in range(n)] for _ in range(n)]
    for i in range(n):
        for j in range(i + 1, n):
            c = libgap.Coefficients(bas, els[i] * els[j]).sage()
            v = V([F(QQ(x)) for x in c])
            t[i][j] = v
            t[j][i] = -v
    return Alg(F, n, t, '%s%d' % (typ, r))


def nilradical(L, R):
    """For an algebra with rational weights: N = {x in R : Tr(R_x R_y) = 0, y in R},
    the common kernel of the weights of R."""
    K = killing(L)
    Rb = R.basis_matrix()
    M = Rb * K * Rb.transpose()
    ker = M.left_kernel()
    return sp(L, [sum((c[i] * R.basis()[i] for i in range(R.dimension())), L.V.zero()) for c in ker.basis()])


