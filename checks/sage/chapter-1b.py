    def relation_lattice(n, prods):
        """Symmetric f on ZZ^n; rows f(e_a e_b, e_c) - f(e_a, e_b e_c)."""
        idx = {}
        for i in range(n):
            for j in range(i, n):
                idx[(i, j)] = idx[(j, i)] = len(set(idx.values()))
        m = len(set(idx.values()))
        tab = {}
        for (i, j), d in prods.items():
            tab[(i, j)] = d
            tab[(j, i)] = {k: -c for k, c in d.items()}
        rows = set()
        for a_ in range(n):
            for b_ in range(n):
                for c_ in range(n):
                    r = [0] * m
                    for k, v in tab.get((a_, b_), {}).items():
                        r[idx[(k, c_)]] += v
                    for k, v in tab.get((b_, c_), {}).items():
                        r[idx[(a_, k)]] -= v
                    rows.add(tuple(r))
        return idx, m, (ZZ ** m).span([vector(ZZ, r) for r in rows], ZZ)

