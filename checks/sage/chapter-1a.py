def gen_alg(F, n, prods, name=''):
    """A general algebra: only the listed products e_i e_j are non-zero."""
    V = VS(F, n)
    t = [[V.zero() for _ in range(n)] for _ in range(n)]
    for (i, j), d in prods.items():
        v = V(0)
        for k, c in d.items():
            v[k] = F(c)
        t[i][j] = v
    return Alg(F, n, t, name)


def current_algebra(A, k):
    """A (x) F[t]/(t^k), basis e_i t^a, index i k + a."""
    n, F = A.n, A.F
    N = n * k
    V = VS(F, N)
    t = [[V.zero() for _ in range(N)] for _ in range(N)]
    for i in range(n):
        for a in range(k):
            for j in range(n):
                for b in range(k):
                    if a + b < k:
                        v = V(0)
                        for l in range(n):
                            v[l * k + a + b] = A.t[i][j][l]
                        t[i * k + a][j * k + b] = v
    return Alg(F, N, t, A.name + '[t]/t^%d' % k)


def cond1(A, ids=None):
    """Condition step:center-condition of th:center-direct-summand."""
    Z = center(A)
    S = prod_space(A, whole(A), whole(A))
    if Z.intersection(S).dimension() != 0:
        return False
    ids = ideals(A) if ids is None else ids
    return all(is_sub(U, Z) for U in ids if prod_space(A, U, U).dimension() == 0)


def cond2(A, ids=None):
    """Condition step:center-summand: L = Z + M, M without solvable ideals."""
    Z = center(A)
    ids = ideals(A) if ids is None else ids
    for M in ids:
        if M.dimension() + Z.dimension() != A.n or M.intersection(Z).dimension() != 0:
            continue
        B = subalg(A, M)
        if all(U.dimension() == 0 or not is_solvable(B, U) for U in ideals(B)):
            return True
    return False


def ideal_checks(A, tag):
    """All theorems on ideals, on all ideals of the finite algebra A."""
    F = A.F
    I = ideals(A)
    L = whole(A)
    S2 = prod_space(A, L, L)
    Z = center(A)
    sol = [U for U in I if is_solvable(A, U)]
    nil = [U for U in I if is_nilpotent(A, U)]
    # th:product-of-ideals
    for U in I:
        for W in I:
            check(is_ideal(A, prod_space(A, U, W)), 'th:product-of-ideals: ' + tag)
    # th:solvable-subalgebra-image
    for U in I:
        Q = quotient(A, U)
        if is_solvable(A, U) and is_solvable(Q):
            check(is_solvable(A)
                  and sol_length(A) <= sol_length(A, U) + sol_length(Q),
                  'th:solvable-subalgebra-image, length <= r + s: ' + tag)
        if is_solvable(A):
            check(is_solvable(Q) and sol_length(Q) <= sol_length(A),
                  'th:solvable-subalgebra-image, image: ' + tag)
    if is_solvable(A):
        for S in subalgebras(A):
            check(is_solvable(A, S) and sol_length(A, S) <= sol_length(A),
                  'th:solvable-subalgebra-image, subalgebra: ' + tag)
    # th:sum-solvable-ideals, th:largest-solvable-ideal
    for U in sol:
        for W in sol:
            check(is_solvable(A, U + W), 'th:sum-solvable-ideals: ' + tag)
    R = zero_sub(A)
    for U in sol:
        R = R + U
    check(is_solvable(A, R) and all(is_sub(U, R) for U in sol),
          'th:largest-solvable-ideal: ' + tag)
    Q = quotient(A, R)
