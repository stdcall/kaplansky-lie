def words(A, leaves, k):
    """Values (with the number of leaves in `I`) of all bracketings of k leaves."""
    if k == 1:
        return set(leaves)
    out = set()
    for a_ in range(1, k):
        for (u, r) in words(A, leaves, a_):
            for (v, s) in words(A, leaves, k - a_):
                w = A.mul(u, v)
                w.set_immutable()
                out.add((w, r + s))
    return out


def chain_basis(F, mats):
    """Book's th:lie-set-triangular-basis: K_0 = 0, K_(i+1) = {v : v S in K_i}, then
    a basis with K_1 last.  Returns the change of basis, or None if the chain stops."""
    N = mats[0].nrows()
    V = VS(F, N)
    K = V.subspace([])
    layers = []
    while K.dimension() < N:
        # v S in K for all S in mats
        if K.dimension() == 0:
            Q = idm(F, N)
        else:
            Q = K.basis_matrix().right_kernel().basis_matrix().transpose()
        K2 = V.subspace(left_ker(F, N, [m * Q for m in mats]).basis())
        K2 = K2 + K
        if K2 == K:
            return None
        new = []
        U = K
        for v in K2.basis():
            if v not in U:
                new.append(v)
                U = U + V.subspace([v])
        layers.append(new)
        K = K2
    rows = [v for layer in reversed(layers) for v in layer]
    return mx(F, rows)


def common_eigenvector(F, mats, N=None):
    """A row vector v != 0 with v M in F v for all M in mats (over F), or None."""
    N = mats[0].nrows() if mats else N
    V = VS(F, N)

    def rec(space, rest):
        if space.dimension() == 0:
            return None
        if not rest:
            return space.basis()[0]
        M = rest[0]
        B = space.basis_matrix()
        # restrict M to `space` if invariant; otherwise test eigenvalues directly
        for lam, _ in M.charpoly().roots():
            E_ = (M - lam * idm(F, N)).left_kernel()
            W = V.subspace(E_.basis()).intersection(space)
            res = rec(W, rest[1:])
            if res is not None:
                return res
        return None

    return rec(V, list(mats))


def triangular_basis(F, mats):
    """A basis with first vector a common eigenvector, etc.; None if there is none.
    In this basis (rows) every matrix is lower triangular (row action)."""
    N = mats[0].nrows()
    V = VS(F, N)
    done = V.subspace([])
    basis = []
    while done.dimension() < N:
        # act on V / done, through a complement
        piv = done.echelonized_basis_matrix().pivots() if done.dimension() else ()
        rest = [i for i in range(N) if i not in piv]
        P = mx(F, list(done.echelonized_basis_matrix().rows()) + [V.gen(i) for i in rest]) \
            if done.dimension() else idm(F, N)
        Pi = P.inverse()
        k = done.dimension()
        qm = [(P * m * Pi).submatrix(k, k) for m in mats]
        v = common_eigenvector(F, qm)
        if v is None:
            return None
        lift = sum((v[i] * V.gen(rest[i]) for i in range(N - k)), V.zero())
        basis.append(lift)
        done = done + V.subspace([lift])
    return mx(F, basis)


def generic(F, gens, names='t'):
    """A polynomial ring over F and the generic combination of matrices."""
    R = PolynomialRing(F, len(gens), names)
    ts = R.gens() if len(gens) > 1 else [R.gen()]
    M = sum((ts[i] * gens[i].change_ring(R) for i in range(len(gens))),
            zero_matrix(R, gens[0].nrows(), gens[0].ncols()))
    return R, ts, M


def rep_of(A, x, mats):
    """S_x for x = sum x_i e_i and S(e_i) = mats[i]."""
    return sum((x[i] * mats[i] for i in range(A.n)), zm(A.F, mats[0].nrows()))


def heis_rep(F):
    """Heisenberg x, y, z (y z = x) on F[t]/(t^p), p the characteristic, row action:
    S_y = d/dt, S_z = multiplication by t, S_x = S_y S_z - S_z S_y = -1."""
    p = F.characteristic()
    D = zm(F, p)
    X = zm(F, p)
    for k_ in range(p):
        if k_ > 0:
            D[k_, k_ - 1] = k_
        if k_ < p - 1:
            X[k_, k_ + 1] = 1
    return [D * X - X * D, D, X]


