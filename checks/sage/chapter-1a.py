def section_2b():
    # th:trace-powers-nilpotent: all 3 x 3 integer matrices with entries -1, 0, 1, exact
    # integer arithmetic: Tr Z = Tr Z^2 = Tr Z^3 = 0 iff Z^3 = 0 (dimension 3: over QQ the
    # hypothesis for n <= 3 implies it for all n by Cayley-Hamilton).
    vals = np.array(list(itertools.product([-1, 0, 1], repeat=9)), dtype=np.int64).reshape(-1, 3, 3)
    Z2 = np.einsum('nij,njk->nik', vals, vals)
    Z3 = np.einsum('nij,njk->nik', Z2, vals)
    tr0 = (np.trace(vals, axis1=1, axis2=2) == 0) & (np.trace(Z2, axis1=1, axis2=2) == 0) \
        & (np.trace(Z3, axis1=1, axis2=2) == 0)
    nil = (Z3 == 0).all(axis=(1, 2))
    check(bool((tr0 == nil).all()) and int(nil.sum()) > 1,
          'th:trace-powers-nilpotent: all 19683 integer matrices with entries in {-1, 0, 1}, p. 28')
    for p in [2, 3, 5, 7]:
        F = GF(p)
        Z = idm(F, p)
        check(all((Z ** k).trace() == 0 for k in range(1, 10)) and not is_nilp_matrix(Z),
              'th:trace-powers-nilpotent needs characteristic 0: the unit p x p matrix')

    # th:sum-commutators-nilpotent, the display of its proof.
    F = QQ
    A1 = E(F, 3, 0, 1) + E(F, 3, 1, 2)
    B1 = diagonal_matrix(F, [0, 1, 2])
    Z = A1 * B1 - B1 * A1
    check(Z == A1 and Z * A1 == A1 * Z and Z * B1 != B1 * Z and is_nilp_matrix(Z),
          'th:sum-commutators-nilpotent: Z commutes with A only, Z is nilpotent')
    pairs_ = [(E(F, 4, 0, 1), E(F, 4, 1, 3)), (E(F, 4, 0, 2), E(F, 4, 2, 3)),
              (E(F, 4, 0, 1) + E(F, 4, 2, 3), E(F, 4, 1, 2))]
    Z = sum((a_ * b_ - b_ * a_ for a_, b_ in pairs_[:2]), zero_matrix(F, 4))
    check(all(Z * a_ == a_ * Z for a_, _ in pairs_[:2]) and is_nilp_matrix(Z),
          'th:sum-commutators-nilpotent, r = 2')
    for n_ in range(1, 5):
        rhs = sum((a_ * (Z ** (n_ - 1) * b_) - (Z ** (n_ - 1) * b_) * a_ for a_, b_ in pairs_[:2]),
                  zero_matrix(F, 4))
        check(Z ** n_ == rhs and rhs.trace() == 0, 'the display in the proof of theorem 18, p. 28')
    for F in [GF(2), GF(3), GF(5)]:
        S = heis_rep(F)
        check(S[0] == S[1] * S[2] - S[2] * S[1] and S[0] * S[1] == S[1] * S[0]
              and not is_nilp_matrix(S[0]),
              'th:sum-commutators-nilpotent needs characteristic 0: d/dt, t on F[t]/(t^p)')

    # th:ideal-invariant-subspace: all ideals, natural and regular representation.
    for F, A in [(GF(3), gl(GF(3), 2)), (GF(2), b_alg(GF(2), 3)), (GF(2), gl(GF(2), 2)),
                 (GF(3), n_alg(GF(3), 3))]:
        for U in ideals(A):
            for mats in (A.rep, A.Rb):
                N = mats[0].nrows()
                V = VS(F, N)
                W = V.subspace([v * rep_of(A, x, mats) for v in V.basis() for x in U.basis()])
                check(all(w * m in W for w in W.basis() for m in mats),
                      'th:ideal-invariant-subspace: ' + A.name)

    # th:faithful-irreducible-nilpotent-ideal, in characteristic p too.
    for F in [GF(2), GF(3), GF(5)]:
        p = F.order()
        L = heis(F, 1)
        S = heis_rep(F)
        check(all(S[i] * S[j] - S[j] * S[i] == rep_of(L, L.t[i][j], S)
                  for i in range(3) for j in range(3)), 'the Heisenberg representation')
