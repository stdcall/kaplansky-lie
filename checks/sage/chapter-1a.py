class Alg:
    def __init__(self, F, n, table, name=''):
        self.F, self.n, self.name = F, n, name
        self.V = VS(F, n)
        self.t = [[self.V(table[i][j]) for j in range(n)] for i in range(n)]
        self.Rb = [mx(F, n, n, [self.t[i][j] for i in range(n)]) for j in range(n)]
        self.Lb = [mx(F, n, n, [self.t[j][i] for i in range(n)]) for j in range(n)]
        self.rep = None

    def R(self, x):
        return sum((x[j] * self.Rb[j] for j in range(self.n)), zm(self.F, self.n))

    def L(self, x):
        return sum((x[j] * self.Lb[j] for j in range(self.n)), zm(self.F, self.n))

    def mul(self, a, b):
        return a * self.R(b)

    def e(self, i):
        return self.V.gen(i)


def lie(F, n, prods, name=''):
    V = VS(F, n)
    t = [[V.zero() for _ in range(n)] for _ in range(n)]
    for (i, j), d in prods.items():
        v = VS(F, n)(0)
        for k, c in d.items():
            v[k] = F(c)
        t[i][j] = v
        t[j][i] = -v
    return Alg(F, n, t, name)


def from_matrices(F, mats, bracket=True, name=''):
    n = len(mats)
    flat = mx(F, [m.list() for m in mats])
    assert flat.rank() == n, 'dependent matrices'

    def coords(m):
        return flat.solve_left(vec(F, m.list()))

    t = [[coords(mats[i] * mats[j] - mats[j] * mats[i] if bracket else mats[i] * mats[j])
          for j in range(n)] for i in range(n)]
    A = Alg(F, n, t, name)
    A.rep = list(mats)
    return A


def E(F, N, i, j):
    m = zm(F, N)
    m[i, j] = 1
    return m


def gl_basis(F, N):
    return [E(F, N, i, j) for i in range(N) for j in range(N)]


def sl_basis(F, N):
    return ([E(F, N, i, j) for i in range(N) for j in range(N) if i != j]
            + [E(F, N, i, i) - E(F, N, i + 1, i + 1) for i in range(N - 1)])


def b_basis(F, N):
    return [E(F, N, i, j) for i in range(N) for j in range(i, N)]


def n_basis(F, N):
    return [E(F, N, i, j) for i in range(N) for j in range(i + 1, N)]


def gl(F, N):
    return from_matrices(F, gl_basis(F, N), name='gl%d' % N)


def sl(F, N):
    return from_matrices(F, sl_basis(F, N), name='sl%d' % N)


def b_alg(F, N):
    return from_matrices(F, b_basis(F, N), name='b%d' % N)


def n_alg(F, N):
    return from_matrices(F, n_basis(F, N), name='n%d' % N)


def sl2_table(F):
    """Basis x, y, h of the hint of exc. 16(a): x h = x, y h = -y, x y = h."""
    return lie(F, 3, {(0, 2): {0: 1}, (1, 2): {1: -1}, (0, 1): {2: 1}}, 'x,y,h')


def so3(F):
    """Vector product, p. 11: a b = c, b c = a, c a = b."""
    return lie(F, 3, {(0, 1): {2: 1}, (1, 2): {0: 1}, (0, 2): {1: -1}}, 'so3')


def ab2(F):
    """Dimension two, p. 13: x y = x."""
    return lie(F, 2, {(0, 1): {0: 1}}, 'ab2')


def abelian(F, n):
    return lie(F, n, {}, 'abelian%d' % n)


def heis(F, r):
    """Basis x, y_1, z_1, ..., y_r, z_r, y_i z_i = x."""
    return lie(F, 2 * r + 1, {(2 * i + 1, 2 * i + 2): {0: 1} for i in range(r)}, 'heis%d' % r)


def filiform(F, n):
    """Basis x, e_1, ..., e_(n-1); x e_i = e_(i+1)."""
    return lie(F, n, {(0, i): {i + 1: 1} for i in range(1, n - 1)}, 'fil%d' % n)


def w3(F):
    """Dimension 5 of the note of p. 50: a b = c, a c = d, b c = e."""
    return lie(F, 5, {(0, 1): {2: 1}, (0, 2): {3: 1}, (1, 2): {4: 1}}, 'w3')


def oscillator(F):
    return lie(F, 4, {(0, 1): {1: 1}, (0, 2): {2: -1}, (1, 2): {3: 1}}, 'osc')


def witt(p):
    F = GF(p)
    prods = {}
    for i in range(p):
        for j in range(i + 1, p):
            prods[(i, j)] = {(i + j) % p: i - j}
    return lie(F, p, prods, 'W%d' % p)


def direct_sum(A, B):
    n = A.n + B.n
    V = VS(A.F, n)
    t = [[V.zero() for _ in range(n)] for _ in range(n)]
    for i in range(A.n):
        for j in range(A.n):
            t[i][j] = V(list(A.t[i][j]) + [0] * B.n)
    for i in range(B.n):
        for j in range(B.n):
            t[A.n + i][A.n + j] = V([0] * A.n + list(B.t[i][j]))
    return Alg(A.F, n, t, A.name + '+' + B.name)


def is_lie(A):
    n = A.n
    for i in range(n):
        if A.t[i][i] != 0:
            return False
        for j in range(i + 1, n):
            if A.t[i][j] != -A.t[j][i]:
                return False
    for i in range(n):
        for j in range(i + 1, n):
            for k in range(j + 1, n):
                if (A.t[i][j] * A.Rb[k] + A.t[j][k] * A.Rb[i] + A.t[k][i] * A.Rb[j]) != 0:
                    return False
    return True


def sp(A, vs):
    return A.V.subspace(list(vs))


def whole(A):
    return A.V


def zero_sub(A):
    return A.V.subspace([])


def prod_space(A, U, W):
    rs = [A.R(w) for w in W.basis()]
    return sp(A, [u * r for u in U.basis() for r in rs])


def derived_series(A, U=None):
    U = whole(A) if U is None else U
    out = [U]
    while True:
        W = prod_space(A, out[-1], out[-1])
        if W == out[-1]:
            return out
        out.append(W)


def lcs(A, U=None):
    """[U_1, U_2, ...], U_1 = U, U_(n+1) = U U_n, up to stabilisation."""
    U = whole(A) if U is None else U
    out = [U]
    while True:
        W = prod_space(A, U, out[-1])
        if W == out[-1]:
            return out
        out.append(W)


def lc_term(ser, i):
    """U_i for i >= 1 from an lcs list."""
    return ser[i - 1] if i <= len(ser) else ser[-1]


def is_solvable(A, U=None):
    return derived_series(A, U)[-1].dimension() == 0


def is_nilpotent(A, U=None):
    return lcs(A, U)[-1].dimension() == 0


def nil_index(A, U=None):
    ser = lcs(A, U)
    assert ser[-1].dimension() == 0
    return len(ser)


def sol_length(A, U=None):
    ser = derived_series(A, U)
    assert ser[-1].dimension() == 0
    return len(ser) - 1


def left_ker(F, n, blocks):
    """Row vectors x with x * B = 0 for all B in blocks."""
    if not blocks:
        return VS(F, n)
    M = block_matrix(F, 1, len(blocks), blocks, subdivide=False, sparse=F.is_finite())
    return M.left_kernel()


def center(A):
    return A.V.subspace(left_ker(A.F, A.n, A.Rb).basis())


def annihilator(A, U):
    return A.V.subspace(left_ker(A.F, A.n, [A.R(u) for u in U.basis()]).basis())


def functionals(A, U):
    """Matrix Q whose right kernel is exactly U."""
    if U.dimension() == 0:
        return idm(A.F, A.n)
    if U.dimension() == A.n:
        return zm(A.F, A.n, 1)
    return U.basis_matrix().right_kernel().basis_matrix().transpose()


def normalizer(A, S):
    Q = functionals(A, S)
    return A.V.subspace(left_ker(A.F, A.n, [A.R(s) * Q for s in S.basis()]).basis())


def is_right_ideal(A, U):
    return all(u * r in U for u in U.basis() for r in A.Rb)


def is_left_ideal(A, U):
    return all(u * r in U for u in U.basis() for r in A.Lb)


def is_ideal(A, U):
    return is_right_ideal(A, U) and is_left_ideal(A, U)


def is_subalgebra(A, U):
    return prod_space(A, U, U).is_subspace(U)


def subalg(A, U):
    """The subalgebra U as an algebra on its basis."""
    B = U.basis_matrix()
    k = B.nrows()
    t = [[U.coordinate_vector(A.mul(B[i], B[j])) for j in range(k)] for i in range(k)]
    return Alg(A.F, k, t, A.name + '|sub')


def quotient(A, U):
    k = U.dimension()
    piv = U.echelonized_basis_matrix().pivots()
    rest = [i for i in range(A.n) if i not in piv]
    P = mx(A.F, list(U.echelonized_basis_matrix().rows()) + [A.e(i) for i in rest])
    Pinv = P.inverse()
    m = A.n - k

    def proj(v):
        return (v * Pinv)[k:]

    t = [[proj(A.mul(A.e(rest[i]), A.e(rest[j]))) for j in range(m)] for i in range(m)]
    Q = Alg(A.F, m, t, A.name + '/I')
    Q.proj = proj
    return Q


def all_subspaces(A):
    """All subspaces of F^n, F finite, from reduced echelon forms."""
    F, n = A.F, A.n
    els = list(F)
    for k in range(n + 1):
        for piv in itertools.combinations(range(n), k):
            free = [(r, c) for r in range(k) for c in range(piv[r] + 1, n) if c not in piv]
            for vals in itertools.product(els, repeat=len(free)):
                M = [[F(0)] * n for _ in range(k)]
                for r in range(k):
                    M[r][piv[r]] = F(1)
                for (r, c), v in zip(free, vals):
                    M[r][c] = v
                yield A.V.subspace([A.V(row) for row in M])


def ideals(A):
    return [U for U in all_subspaces(A) if is_ideal(A, U)]


def subalgebras(A):
    return [U for U in all_subspaces(A) if is_subalgebra(A, U)]


def killing(A):
    return mx(A.F, A.n, A.n, lambda i, j: (A.Rb[i] * A.Rb[j]).trace())


def trace_form(F, mats):
    n = len(mats)
    return mx(F, n, n, lambda i, j: (mats[i] * mats[j]).trace())


def invariant_forms(A):
    """Basis of the symmetric bilinear f with f(a b, c) = f(a, b c)."""
    n = A.n
    idx = {}
    for i in range(n):
        for j in range(i, n):
            idx[(i, j)] = idx[(j, i)] = len(set(idx.values()))
    m = len(set(idx.values()))
    rows = set()
    for a in range(n):
        for b in range(n):
            for c in range(n):
                row = [A.F(0)] * m
                ab = A.t[a][b]
                bc = A.t[b][c]
                for k in range(n):
                    if ab[k] != 0:
                        row[idx[(k, c)]] += ab[k]
                    if bc[k] != 0:
                        row[idx[(a, k)]] -= bc[k]
                rows.add(tuple(row))
    M = mx(A.F, sorted(rows, key=str)) if rows else zm(A.F, 1, m)
    out = []
    for sol in M.right_kernel().basis():
        out.append(mx(A.F, n, n, lambda i, j: sol[idx[(i, j)]]))
    return out


def derivations(A):
    """Basis of Der(A) as n x n matrices acting on the right of row vectors."""
    n = A.n
    F = A.F
    rows = []
    for a in range(n):
        for b in range(n):
            # (e_a e_b) D = (e_a D) e_b + e_a (e_b D), coordinates in e_k
            eqs = [dict() for _ in range(n)]
            ab = A.t[a][b]
            for i in range(n):
                if ab[i] != 0:
                    for k in range(n):
                        eqs[k][(i, k)] = eqs[k].get((i, k), F(0)) + ab[i]
            for l in range(n):
                v = A.t[l][b]
                for k in range(n):
                    if v[k] != 0:
                        eqs[k][(a, l)] = eqs[k].get((a, l), F(0)) - v[k]
                w = A.t[a][l]
                for k in range(n):
                    if w[k] != 0:
                        eqs[k][(b, l)] = eqs[k].get((b, l), F(0)) - w[k]
            for eq in eqs:
                if any(c != 0 for c in eq.values()):
                    r = [F(0)] * (n * n)
                    for (i, k), c in eq.items():
                        r[i * n + k] = c
                    rows.append(r)
    if rows:
        M = mx(F, rows)
        sols = M.right_kernel().basis()
    else:
        sols = VS(F, n * n).basis()
    return [mx(F, n, n, list(s)) for s in sols]


def centroid(A):
    """Linear theta with (a b) theta = (a theta) b = a (b theta)."""
    n = A.n
    F = A.F
    rows = []
    for a in range(n):
        for b in range(n):
            ab = A.t[a][b]
            for k in range(n):
                r1 = [F(0)] * (n * n)
                r2 = [F(0)] * (n * n)
                for i in range(n):
                    if ab[i] != 0:
                        r1[i * n + k] += ab[i]
                        r2[i * n + k] += ab[i]
                for l in range(n):
                    if A.t[l][b][k] != 0:
                        r1[a * n + l] -= A.t[l][b][k]
                    if A.t[a][l][k] != 0:
                        r2[b * n + l] -= A.t[a][l][k]
                rows.append(r1)
                rows.append(r2)
    sols = mx(F, rows).right_kernel().basis()
    return [mx(F, n, n, list(s)) for s in sols]


def is_derivation(A, D):
    return all(A.t[a][b] * D == (A.e(a) * D) * A.Rb[b] + A.e(a) * A.R(A.e(b) * D)
               for a in range(A.n) for b in range(A.n))


def is_automorphism(A, T):
    return T.is_invertible() and all(
        A.t[a][b] * T == A.mul(A.e(a) * T, A.e(b) * T) for a in range(A.n) for b in range(A.n))


def is_nilp_matrix(M):
    return (M ** M.nrows()).is_zero()


def gen_eigenspace(T, lam):
    n = T.nrows()
    return ((T - lam * idm(T.base_ring(), n)) ** n).left_kernel()


def rational_roots(T):
    return [r for r, _ in T.charpoly().roots()]


def gens_of(U):
    return list(U.basis())


def irreducible_mtx(mats, F):
    """GAP MeatAxe: (irreducible, absolutely irreducible)."""
    gmats = [libgap([[libgap(F(c)) for c in row] for row in m.rows()]) for m in mats]
    gm = libgap.GModuleByMats(gmats, libgap(F))
    return (bool(libgap.eval('MTX.IsIrreducible')(gm)),
            bool(libgap.eval('MTX.IsAbsolutelyIrreducible')(gm)))


def v_k(F, k):
    """The (k+1)-dimensional sl_2-module: matrices e, f, h with [e,f]=h."""
    N = k + 1
    e_ = zm(F, N)
    f_ = zm(F, N)
    h_ = zm(F, N)
    for i in range(N):
        h_[i, i] = k - 2 * i
    for i in range(N - 1):
        f_[i + 1, i] = i + 1
        e_[i, i + 1] = k - i
    assert e_ * f_ - f_ * e_ == h_
    return e_, f_, h_


def affine(F, rho_basis, N):
    """L = {[[A, v], [0, 0]]}: A in the span of rho_basis (N x N), v a column."""
    mats = []
    for m in rho_basis:
        M = zm(F, N + 1)
        M.set_block(0, 0, m)
        mats.append(M)
    for i in range(N):
        M = zm(F, N + 1)
        M[i, N] = 1
        mats.append(M)
    return mats


def sl2_v(F, k):
    e_, f_, h_ = v_k(F, k)
    return from_matrices(F, affine(F, [e_, f_, h_], k + 1), name='sl2xV%d' % k)


def is_sub(U, W):
    return U.is_subspace(W)


