class Orbits3:
    """Structures: rows e_0 e_1, e_0 e_2, e_1 e_2; codes in the field list."""

    def __init__(self, q):
        self.q = q
        self.F = GF(q, 'w') if not Integer(q).is_prime() else GF(q)
        F = self.F
        rest = [x for x in F if x not in (F(0), F(1))]
        self.els = [F(0), F(1)] + sorted(rest, key=str)
        self.idx = {x: i for i, x in enumerate(self.els)}
        idx = self.idx
        self.add = np.array([[idx[a + b] for b in self.els] for a in self.els], dtype=np.int64)
        self.mul = np.array([[idx[a * b] for b in self.els] for a in self.els], dtype=np.int64)
        self.neg = np.array([idx[-a] for a in self.els], dtype=np.int64)
        self._enumerate()
        self._orbits()

    def _enumerate(self):
        q, add, mul, neg = self.q, self.add, self.mul, self.neg
        grid = np.array(np.meshgrid(*[np.arange(q)] * 6, indexing='ij')).reshape(6, -1)
        c13, c23 = grid[:3], grid[3:]
        out = []
        for c12 in itertools.product(range(q), repeat=3):
            ok = np.ones(c13.shape[1], dtype=bool)
            for k in range(3):
                t1 = add[mul[c12[0], c13[k]], mul[c12[1], c23[k]]]
                t2 = add[neg[mul[c23[1], c12[k]]], neg[mul[c23[2], c13[k]]]]
                t3 = add[neg[mul[c13[0], c12[k]]], mul[c13[2], c23[k]]]
                ok &= add[add[t1, t2], t3] == 0
            sel = np.nonzero(ok)[0]
            arr = np.zeros((len(sel), 9), dtype=np.int64)
            arr[:, 0:3] = c12
            arr[:, 3:6] = c13[:, sel].T
            arr[:, 6:9] = c23[:, sel].T
            out.append(arr)
        arr = np.concatenate(out)
        codes = arr.dot(q ** np.arange(9, dtype=np.int64))
        order = np.argsort(codes)
        self.arr, self.codes = arr[order], codes[order]

    def _transform(self, G):
        """All structures in the basis e'_i = sum G_ia e_a; returns positions."""
        F, idx, add, mul = self.F, self.idx, self.add, self.mul
        pairs = [(0, 1), (0, 2), (1, 2)]
        Ginv = G.inverse()
        L2 = mx(F, 3, 3, lambda r, s: G[pairs[r][0], pairs[s][0]] * G[pairs[r][1], pairs[s][1]]
                    - G[pairs[r][0], pairs[s][1]] * G[pairs[r][1], pairs[s][0]])
        L2c = np.array([[idx[L2[r, s]] for s in range(3)] for r in range(3)])
        Gic = np.array([[idx[Ginv[r, s]] for s in range(3)] for r in range(3)])
        N = len(self.codes)
        C = self.arr.reshape(N, 3, 3)
        D = np.zeros_like(C)
        Ec = np.zeros_like(C)
        for r in range(3):
            for k in range(3):
                t = np.zeros(N, dtype=np.int64)
                for s in range(3):
                    t = add[t, mul[L2c[r, s], C[:, s, k]]]
                D[:, r, k] = t
        for r in range(3):
            for k in range(3):
                t = np.zeros(N, dtype=np.int64)
                for s in range(3):
                    t = add[t, mul[D[:, r, s], Gic[s, k]]]
                Ec[:, r, k] = t
        nc = Ec.reshape(N, 9).dot(self.q ** np.arange(9, dtype=np.int64))
        pos = np.searchsorted(self.codes, nc)
        assert (self.codes[pos] == nc).all()
        return pos

    def _orbits(self):
        F = self.F
        N = len(self.codes)
        parent = list(range(N))

        def find(x):
            while parent[x] != x:
                parent[x] = parent[parent[x]]
                x = parent[x]
            return x

        g = F.multiplicative_generator()
        gens = [mx(F, [[1, 1, 0], [0, 1, 0], [0, 0, 1]]),
                mx(F, [[0, 1, 0], [0, 0, 1], [1, 0, 0]]),
                mx(F, [[g, 0, 0], [0, 1, 0], [0, 0, 1]])]
        for G in gens:
            pos = self._transform(G)
            for i in range(N):
                a, b = find(i), find(int(pos[i]))
                if a != b:
                    parent[a] = b
        self.root = np.array([find(i) for i in range(N)])
        self.reps, self.sizes = np.unique(self.root, return_counts=True)

    def alg_of(self, pos):
        row = self.arr[pos]
        F = self.F
        vs = [vec(F, [self.els[c] for c in row[3 * i:3 * i + 3]]) for i in range(3)]
        V = VS(F, 3)
        t = [[V.zero() for _ in range(3)] for _ in range(3)]
        t[0][1], t[0][2], t[1][2] = vs
        t[1][0], t[2][0], t[2][1] = -vs[0], -vs[1], -vs[2]
        return Alg(F, 3, t, 'q%d#%d' % (self.q, pos))

    def label(self, A):
        """The orbit (root position) of a 3-dimensional algebra over the same field."""
        row = [self.idx[A.t[0][1][k]] for k in range(3)] + [self.idx[A.t[0][2][k]] for k in range(3)] \
            + [self.idx[A.t[1][2][k]] for k in range(3)]
        code = int(np.array(row, dtype=np.int64).dot(self.q ** np.arange(9, dtype=np.int64)))
        pos = int(np.searchsorted(self.codes, code))
        assert int(self.codes[pos]) == code
        return int(self.root[pos])


def t_algebra(F, T):
    """L^2 = <x, y> abelian, z acts on it by the 2 x 2 matrix T: x z, y z = rows of T."""
    V = VS(F, 3)
    t = [[V.zero() for _ in range(3)] for _ in range(3)]
    t[0][2] = V(list(T[0]) + [0])
    t[1][2] = V(list(T[1]) + [0])
    t[2][0] = -t[0][2]
    t[2][1] = -t[1][2]
    return Alg(F, 3, t, 'T')


