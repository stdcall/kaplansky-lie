def mx(F, *args, **kwds):
    return matrix(F, *args, sparse=F.is_finite(), **kwds)


def zm(F, r, c=None):
    return zero_matrix(F, r, r if c is None else c, sparse=F.is_finite())


def idm(F, n):
    return identity_matrix(F, n, sparse=F.is_finite())


def VS(F, n):
    return VectorSpace(F, n, sparse=F.is_finite())


def vec(F, entries):
    entries = list(entries)
    return VS(F, len(entries))(entries)


def vectors(F, n):
    """All vectors of F^n, F finite."""
    return iter(VS(F, n))


