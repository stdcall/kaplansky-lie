    # Exercise 15.
    def is_invariant_form(A, g):
        return all(A.t[a_][b_] * g * A.e(c_) == A.e(a_) * g * A.t[b_][c_]
                   for a_ in range(A.n) for b_ in range(A.n) for c_ in range(A.n))

    def form_theta(f, th):
        # g(a, b) = f(a th, b): the matrix of g in the basis
        return th * f

