    # 2 a = 0 implies a = 0: x x = x over GF(2) has a b = - b a but not a^2 = 0.
    check((a + b) * (a + b) - a * a - b * b == a * b + b * a, "eq:anticommutative, p. 9")
    A = Alg(GF(2), 1, [[vec(GF(2), [1])]], 'idem')
